#!/usr/bin/env python3

from __future__ import annotations

import argparse
import hashlib
import json
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from app.version import __version__
from tools.verify_release import sha256, verify

INCLUDE_DIRS = ("neural_network", "training", "app", "frontend", "tools", "tests", "docs", "configs")
INCLUDE_FILES = ("README.md", "requirements.txt", "train.py", ".gitignore", ".dockerignore", "Dockerfile", "CHANGELOG.md", "LICENSE")
SKIP_PARTS = {"__pycache__", "node_modules", ".git", "dist", ".venv"}


def release_notes(root: Path) -> str:
    meta = json.loads((root / "models" / "synapse_v1.json").read_text())
    ev, cfg = meta["evaluation"], meta["training_config"]
    tr, ood = cfg["training"], json.loads((root / "experiments" / "ood_eval.json").read_text())
    pipe = json.loads((root / "experiments" / "pipeline_eval.json").read_text())
    size_mb = (root / "models" / "synapse_v1.npz").stat().st_size / 1e6
    c = ood["categories"]
    rows = "\n".join(f"| {k} | {v['reject_rate']:.1%} | {v['false_accepts']} / {v['n']} |" for k, v in c.items() if not k.startswith("valid"))
    canvas = pipe["canvas_pipeline"]
    first, thick = canvas["extra_stroke_width_0px"], canvas["extra_stroke_width_16px"]
    return f"""# Synapse {__version__} release notes

Generated by `tools/package_release.py` from the files in this archive. Every number below is read from
those files; none is typed by hand.

## Release identity

- App version {__version__}, model version {meta['model_version']}
- Training run: `{meta['run_id']}`
- Weights: `models/synapse_v1.npz`, SHA-256 `{meta['npz_sha256']}`
- Created: {meta['created_utc']}
- Consistency: `python tools/verify_release.py` must print "release consistent".

## Model

- Architecture {cfg['model']['layer_sizes']}, {meta['parameter_count']:,} parameters, {cfg['model']['dtype']}, {size_mb:.3f} MB
- Training: {tr['optimizer']} lr {tr['learning_rate']} ({tr['lr_schedule']}), weight decay {tr['weight_decay']}, batch {tr['batch_size']},
  augmentation {'on' if tr['augmentation']['enabled'] else 'off'}, {meta['metrics_report']['epochs_run']} epochs, checkpoint epoch {meta['best_epoch']} (lowest validation loss), seed {tr['seed']}
- Data: {meta['dataset']['n_train']:,} train / {meta['dataset']['n_val']:,} validation / {meta['dataset']['n_test']:,} test (MNIST digits 1-9)

## Measured results

| Metric | Value |
|---|---|
| Test accuracy (official MNIST test set, evaluated once) | {ev['test_accuracy']:.2%} |
| Validation accuracy | {ev['validation_accuracy']:.2%} |
| Test macro F1 | {ev['test_macro_f1']:.4f} |
| Calibration error (ECE, test) | {ev['test_ece']:.4f} |
| Single-sample latency, median / p95 (at training time) | {ev['latency']['median_ms']:.3f} / {ev['latency']['p95_ms']:.3f} ms |

Latency depends on the machine and load and is re-measured on every run; accuracy is deterministic for a given seed and BLAS.

## Drawing pipeline (`experiments/pipeline_eval.md`)

MNIST digits re-rendered as canvas drawings and passed through the browser's preprocessing: {first['accuracy']:.2%} accuracy with the native stroke width
(native 28x28: {pipe['native_mnist_28x28']['accuracy']:.2%}); {thick['accuracy']:.2%} with 16 px extra stroke thickness. Re-rendered MNIST tests geometry and stroke width, not real handwriting.
JS vs Python preprocessing: max pixel difference {pipe['js_vs_python']['max_pixel_difference']}, prediction agreement {pipe['js_vs_python']['prediction_agreement']:.1%}.

## Rejecting input that is not a digit (`experiments/ood_eval.md`)

Reject threshold {ood['threshold']:.4f} (95% of valid validation digits accepted). **Rejection is not universal:**

| Input | Rejected | Falsely accepted |
|---|---|---|
{rows}

Max-softmax confidence is a heuristic. It stops blank canvases, dots and noise, and rejects most scribbles and shapes, but accepts many letters and symbols.

## Known limits

- Accuracy figures are for MNIST digits; real handwriting varies. Use the UI's "Teach the network" flow to adapt to yours.
- Very thick pen strokes reduce accuracy (see the pipeline table).
- Models trained in the UI are validated on the MNIST validation split only; the test set is reserved for the release model.
- The server is unauthenticated and intended for localhost. Use `--read-only` if you expose it.
"""


def collect(root: Path, with_data: bool, run_id: str) -> list[Path]:
    files: list[Path] = []
    for d in INCLUDE_DIRS:
        for p in sorted((root / d).rglob("*")):
            if p.is_file() and not (SKIP_PARTS & set(p.relative_to(root).parts)) and p.suffix not in (".pyc",):
                files.append(p)
    files += [root / f for f in INCLUDE_FILES if (root / f).exists()]
    files += [root / "models" / "synapse_v1.npz", root / "models" / "synapse_v1.json"]
    for p in sorted((root / "experiments" / "runs" / run_id).rglob("*")):
        if p.is_file():
            files.append(p)
    for f in ("ood_eval.json", "ood_eval.md", "pipeline_eval.json", "pipeline_eval.md"):
        files.append(root / "experiments" / f)
    if with_data:
        files += sorted((root / "data" / "mnist").glob("*.gz"))
    return files


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Verify the release, then build the ZIP with a SHA-256 manifest and generated release notes.", epilog="writes dist/Shadowcr3-Synapse-<version>.zip",
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(ROOT))
    ap.add_argument("--out", default="dist")
    ap.add_argument("--no-data", action="store_true", help="omit MNIST (it is re-downloaded and hash-verified on demand)")
    args = ap.parse_args(argv)
    root = Path(args.root)

    problems = verify(root)
    if problems:
        print("refusing to package an inconsistent release:\n  - " + "\n  - ".join(problems), file=sys.stderr)
        return 1
    meta = json.loads((root / "models" / "synapse_v1.json").read_text())
    notes = release_notes(root)
    (root / "RELEASE_NOTES.md").write_text(notes, encoding="utf-8")

    files = collect(root, not args.no_data, meta["run_id"]) + [root / "RELEASE_NOTES.md"]
    manifest = {"name": "shadowcr3-synapse", "version": __version__, "model_version": meta["model_version"], "run_id": meta["run_id"],
                "npz_sha256": meta["npz_sha256"], "files": {str(p.relative_to(root)): sha256(p) for p in files}}
    out = Path(args.out); out.mkdir(parents=True, exist_ok=True)
    zpath = out / f"Shadowcr3-Synapse-{__version__}.zip"
    zpath.unlink(missing_ok=True)
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for p in files:
            z.write(p, f"Shadowcr3-Synapse/{p.relative_to(root)}")
        z.writestr("Shadowcr3-Synapse/MANIFEST.json", json.dumps(manifest, indent=2))

    with zipfile.ZipFile(zpath) as z:
        bad = z.testzip()
        man = json.loads(z.read("Shadowcr3-Synapse/MANIFEST.json"))
        mismatches = [n for n, h in man["files"].items()
                      if hashlib.sha256(z.read(f"Shadowcr3-Synapse/{n}")).hexdigest() != h]
    if bad or mismatches:
        print(f"ZIP verification failed: {bad or mismatches}", file=sys.stderr)
        return 1
    print(f"{zpath}  ({zpath.stat().st_size / 1e6:.1f} MB, {len(man['files'])} files + manifest)")
    print(f"run {meta['run_id']}; npz sha256 {meta['npz_sha256'][:16]}…; manifest verified")
    return 0


if __name__ == "__main__":
    sys.exit(main())
